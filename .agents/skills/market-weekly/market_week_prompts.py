"""agy prompt instructions for Taiwan market weekly digest."""

from __future__ import annotations

FORMAT_RULES = """
輸出格式（Markdown）：
- 只能使用下方 facts 與新聞；不可發明未列出的類股名稱或權值股代號
- 數字方向（漲跌、強弱、超額正負、美股週報酬）必須與 facts 一致
- 不可寫保證漲跌、目標價、穩賺、一定漲
- 不可用美股敘事推翻台股 facts 的方向數字

## 一、本週大盤總評
**純文字** 2～4 句，說明加權指數本週報酬、收在週區間位置與整體風險偏好。
可一句帶過外生（那指／費半）風險偏好，但禁止重抄完整美股數字表。

## 二、權值帶動結構
**純文字** 或短條列：說明哪些權值／廣基 ETF 相對帶動或拖累（須引用 facts 中的代號與週報酬／超額）。

## 三、類股強弱
說明強勢／弱勢類股（名稱必須出自 facts 的強勢／弱勢榜），並點出相對大盤超額。

## 四、交叉解讀
**必須使用** 2～4 點 `-` 開頭條列。
- **台美對帳（必做，若 us.available）**：須有 1～2 點，每點引用那斯達克（那指）與／或費半的週報酬數字，以及對應台股數字（大盤與／或半導體類指數），並使用 facts.alignment 的判定詞 **一致** 或 **背離**（不可改寫）。
  - 「落後」僅可在 gaps 明顯時補充說明幅度／節奏，不可發明與 facts 相反的漲跌方向。
- 若 us.available 為 false：寫一句「本週美股指數資料不足」，再做台股結構交叉。
- 若上方提供對帳新聞：每一點須（1）**原文引用**提供的新聞標題（勿改寫）；（2）引用至少一個 facts 數字（大盤週報酬／權值週報酬或超額／類股週報酬或超額／美股週報酬）；（3）明確寫出關係判定：**一致**／**背離**／**資訊落後**（於價格）。
- 若無可用新聞：寫一句「本週無可對帳新聞」，再以大盤×權值×類股（及台美）做結構交叉。
- 禁止用新聞改寫或推翻 facts 的方向數字。

## 五、下週情境推演
2～3 種情境，每種須含「觸發條件」與「可追蹤訊號」；不可保證漲跌。
當 us.available 時：**至少 1 個情境**的觸發條件須綁費半或那指（例：費半週報酬轉弱、那指守住本週區間）。

## 六、觀察重點
編號 3～5 項，每項一句可追蹤指標。

## 七、免責聲明
一句話免責。
""".strip()


def build_market_week_prompt(
    *,
    facts_summary: str,
    news_section: str,
) -> str:
    news_block = (
        news_section.strip()
        if news_section.strip()
        else "（本週未提供可用新聞；交叉段請寫「本週無可對帳新聞」並改做結構交叉）"
    )
    return (
        "這是「台股市場週報」任務：依系統確定性 facts 撰寫本週總評與下週展望。\n"
        "類股來自證交所官方類股指數，不是個人持股觀察池。\n"
        "交叉解讀的目的是用市場數字佐證或對質新聞，並做台股×那指／費半對帳，不是把新聞當氣氛。\n\n"
        f"=== 系統市場週事實（facts）===\n{facts_summary}\n"
        f"=== facts 結束 ===\n\n"
        f"=== 新聞（未驗證軟脈絡；標題須原文引用）===\n{news_block}\n"
        f"=== 新聞結束 ===\n\n"
        f"{FORMAT_RULES}\n\n"
        "其他要求：\n"
        "- 完整正文印在 stdout\n"
        "- 不要加工作摘要或工具操作說明\n"
        "- 正文須引用至少 2 條 anchors（或等價的事實數字）\n"
    )


def build_fix_prompt(*, base_prompt: str, issues: list[str]) -> str:
    bullet = "\n".join(f"- {item}" for item in issues)
    return (
        f"{base_prompt}\n\n"
        "上一版未通過驗證，請依下列問題修正後重寫完整正文：\n"
        f"{bullet}\n"
    )
