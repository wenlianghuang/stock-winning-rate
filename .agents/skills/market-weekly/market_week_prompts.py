"""agy prompt instructions for Taiwan market weekly digest."""

from __future__ import annotations

FORMAT_RULES = """
輸出格式（Markdown）：
- 只能使用下方 facts 與新聞；不可發明未列出的類股名稱或權值股代號
- 數字方向（漲跌、強弱、超額正負、美股週報酬）必須與 facts 一致
- 不可寫保證漲跌、目標價、穩賺、一定漲
- 不可用美股敘事推翻台股 facts 的方向數字
- **篇幅重心在「五、下週情境推演」**（應佔全文一半以上）；一～三保持精簡，勿把表格重念一遍

## 一、本週大盤總評
**純文字** 2～3 句即可：加權週報酬、收在週區間位置、風險偏好一句帶過。
可一句帶外生（那指／費半），禁止重抄完整美股數字表。

## 二、權值帶動結構
**最多 4～6 行**：點出主要帶動／拖累各 2～3 檔（須含代號與週報酬或超額），不要逐檔製表。

## 三、類股強弱
**短條列**：強勢／弱勢各點 2～3 名與相對大盤超額即可。

## 四、交叉解讀
**必須使用** 2～4 點 `-` 開頭條列（為第五章鋪陳，勿寫成長文）。
- **台美對帳（必做，若 us.available）**：1～2 點，引用那指／費半數字 + 台股對應數字，使用 facts.alignment 的 **一致** 或 **背離**。
  - 「落後」僅可在 gaps 明顯時補充幅度／節奏，不可發明反向數字。
- 若 us.available 為 false：寫「本週美股指數資料不足」。
- 若有對帳新聞：原文引用標題 + facts 數字 + **一致**／**背離**／**資訊落後**。
- 若無新聞：寫「本週無可對帳新聞」，再做結構交叉。
- 禁止用新聞推翻 facts 方向。

## 五、下週情境推演（核心；請盡量寫完整）
讀者情境：**週末無交易，卻必須依本報告決定週一如何應對。**
本章是全文最重要段落，請寫厚、寫清楚、可執行；不可只列三句口號。

### 5.0 開場（必寫，3～5 句）
- 用本週 facts 結構總結「進入下週的起手盤」（例：權值護盤／廣基擴散／台美背離／防禦輪動）。
- 明確說明：**對週一開盤最關鍵的 1～2 個變數**（須可對應 facts 標的或指數）。

### 5.1 情境排序（必寫 3 種）
依**本週結構連貫性**排序（不是隨意列），標題必須標明：
- **基準／最可能**
- **次可能**
- **尾部風險**

每一情境**各自**須含下列子項（可用小標或 `-`）：
1. **結構連貫**：為何此路徑與本週大盤×權值×類股×（若有）台美對帳一致或銜接。
2. **觸發條件**：週末至週一可發生、可觀測的條件（若／一旦／觸發）。
3. **週一開盤含義**：開盤強／弱／震盪時，對大盤與權值結構意味什麼（描述狀態，**不要**下買賣指令或目標價）。
4. **可追蹤訊號**：2～3 個盤中／收盤可對照的指標（指數點位、權值代號、類股超額、那指／費半等，須出自 facts）。
5. **否決條件**：出現什麼訊號就應放棄此情境假設（必寫「否決」二字）。

當 us.available 時：至少一個情境的觸發或訊號須綁費半或那指。

### 5.2 週一決策儀表板（必寫）
用條列整理「週一開盤後 30～60 分鐘可對照」的檢核清單（至少 4 項），每項一句：
觀察什麼 → 若出現 → 較支持哪一情境。
禁止保證獲利；可寫風險偏好／結構假設的切換條件。

## 六、觀察重點
編號 4～6 項，**從第五章訊號收斂**，每項一句可追蹤指標；不要重抄完整報酬表。

## 七、免責聲明
一句話免責：僅供參考，不構成投資建議。
""".strip()


def build_market_week_prompt(
    *,
    facts_summary: str,
    news_section: str,
) -> str:
    news_block = (
        news_section.strip()
        if news_section.strip()
        else "（本週未提供可用新聞；交叉段請寫「本週無可對帳新聞」並改做結構交叉）"
    )
    return (
        "這是「台股市場週報」任務：依系統確定性 facts 撰寫本週總評與下週展望。\n"
        "類股來自證交所官方類股指數，不是個人持股觀察池。\n"
        "讀者最關心的是假日無法交易、卻要為週一做準備——因此「下週情境推演」必須寫得完整、可執行。\n"
        "交叉解讀為情境鋪陳；數字儀表板已另有 UI，勿把一～三寫成 facts 朗讀。\n\n"
        f"=== 系統市場週事實（facts）===\n{facts_summary}\n"
        f"=== facts 結束 ===\n\n"
        f"=== 新聞（未驗證軟脈絡；標題須原文引用）===\n{news_block}\n"
        f"=== 新聞結束 ===\n\n"
        f"{FORMAT_RULES}\n\n"
        "其他要求：\n"
        "- 完整正文印在 stdout\n"
        "- 不要加工作摘要或工具操作說明\n"
        "- 正文須引用至少 2 條 anchors（或等價的事實數字）\n"
        "- 第五章篇幅應明顯長於其他章節總和\n"
    )


def build_fix_prompt(*, base_prompt: str, issues: list[str]) -> str:
    bullet = "\n".join(f"- {item}" for item in issues)
    return (
        f"{base_prompt}\n\n"
        "上一版未通過驗證，請依下列問題修正後重寫完整正文：\n"
        f"{bullet}\n"
        "特別注意：若問題與情境／週一／否決／排序有關，請優先加厚第五章，勿只改關鍵字。\n"
    )
