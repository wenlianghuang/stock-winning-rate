"""Shared agy prompt instructions for portfolio narratives.

The deterministic holdings table (weights/amounts) is inserted by the report
harness; agy only writes the *narrative*. Numbers stay owned by Python.
"""

from __future__ import annotations

PORTFOLIO_FORMAT_RULES = """
輸出格式（Markdown）：
- 對象是**完全沒有投資經驗的新手**，請用白話、口語、避免術語；必要術語要一句話解釋。
- **不要**重複列出權重百分比、投入金額、股數等數字（系統會自動在報告前段插入配置表格）。
- 敘述方向與角色**不可與系統事實（facts）矛盾**：核心 ETF 就說是核心、衛星個股就說是衛星。
- **不可**把系統未選入的股票寫成建議買進/納入的持股；只能討論表格中的持股。
- **不可**出現「保證」「穩賺」「一定漲」「目標價」等字眼。

## 一、一句話總結
用 1～2 句話說明這是什麼樣的組合、適合什麼樣的人（對齊風險屬性）。

## 二、這個組合適合誰
**純文字** 2～4 句，說明為什麼這個配置符合此風險屬性（例如：波動大小、是否穩健、適合的投資時間長短）。

## 三、每檔為什麼選它
**純文字**條列（每檔一項，`-` 開頭），用白話解釋每一檔為什麼被選入、它在組合中扮演什麼角色（核心/衛星、穩定/成長），依據系統提供的理由，不要編造數字。

## 四、這個組合的風險
**純文字** 2～4 句，說明整體風險等級與預期波動代表什麼、最壞情況大概是什麼感覺、要放多久；若系統有警示，須誠實提到。

## 五、新手紀律（最重要）
**純文字**條列（至少 3 點），必須涵蓋：**下跌時該怎麼想/怎麼做**、**分批進場**、**多久檢視一次與再平衡**。

## 六、免責聲明
一句話免責：僅供教育參考、非投資建議、投資有風險。
""".strip()


THEME_FORMAT_RULES = """
輸出格式（Markdown）：
- 對象是**有投資經驗、想配置主題袖口**的使用者（可能已有其他部位）。
- **不要**重複列出權重百分比、投入金額、股數等數字（系統會自動在報告前段插入配置表格）。
- 敘述**不可與系統事實（facts）矛盾**：主題、角色、產業必須對齊。
- **不可**把系統未選入的股票寫成建議買進/納入的持股；只能討論表格中的持股。
- **不可**出現「保證」「穩賺」「一定漲」「目標價」等字眼。
- **不可**把主題袖口說成「穩健分散的全市場組合」或「低風險保本」。

## 一、一句話總結
用 1～2 句話說明這是哪個主題的袖口組合、適合什麼用途（例如：既有部位外加金融曝險）。

## 二、這個組合適合誰
**純文字** 2～4 句，說明適合誰、不適合誰；須點出「主題集中／袖口」特性。

## 三、每檔為什麼選它
**純文字**條列（每檔一項，`-` 開頭），依系統提供的籌碼／基本面理由說明為何入選，不要編造數字。

## 四、這個組合的風險
**純文字** 2～4 句，必須說明主題集中風險與預期波動；若系統有警示須誠實提到；融合主題須點出不同主題風險可能不同。

## 五、部位紀律
**純文字**條列（至少 3 點），必須涵蓋：**下跌/主題退潮時怎麼想**、**分批進場**、**定期檢視主題是否仍成立**。

## 六、免責聲明
一句話免責：僅供教育參考、非投資建議、投資有風險。
""".strip()


def build_portfolio_analysis_prompt_suffix(
    *,
    profile_label: str,
    risk_label: str,
    facts_summary: str,
    mode: str = "beginner",
) -> str:
    if mode == "theme":
        return (
            f"這是一份「主題投資組合（袖口）」的撰寫任務。\n"
            f"系統已依規則**確定性地**在主題候選池完成選股與配權重，下方 facts 即唯一事實來源；"
            f"請**依 facts 撰寫說明正文**（Markdown），"
            f"不要自行更動權重、金額或加入未列出的股票。\n\n"
            f"組合名稱：{profile_label}（{risk_label}）\n\n"
            f"=== 系統組合事實（facts）===\n{facts_summary}\n"
            f"=== facts 結束 ===\n\n"
            f"{THEME_FORMAT_RULES}\n\n"
            "其他要求：\n"
            "- 全程使用繁體中文，語氣清楚、對有經驗的投資人說明即可。\n"
            "- 必須強調這是主題袖口而非全倉分散。\n"
            "- 每一檔持股都要在「每檔為什麼選它」出現並給理由。\n"
            "- 風險段須說明主題集中風險；紀律段須具體可執行。\n"
            "- 完整正文印在 stdout，不要只寫入檔案。\n"
            "- 不要加「工作摘要」或工具操作說明。\n"
        )

    return (
        f"這是一份「新手投資組合建議」的撰寫任務。\n"
        f"系統已依規則**確定性地**完成選股與配權重，下方 facts 即唯一事實來源；"
        f"請**依 facts 撰寫給新手看的說明正文**（Markdown），"
        f"不要自行更動權重、金額或加入未列出的股票。\n\n"
        f"風險屬性：{profile_label}（{risk_label}）\n\n"
        f"=== 系統組合事實（facts）===\n{facts_summary}\n"
        f"=== facts 結束 ===\n\n"
        f"{PORTFOLIO_FORMAT_RULES}\n\n"
        "其他要求：\n"
        "- 全程使用繁體中文，語氣親切、像在對第一次買股票的朋友說明。\n"
        "- 角色（核心 ETF／衛星個股）與產業描述須與 facts 一致。\n"
        "- 每一檔持股都要在「每檔為什麼選它」出現並給理由。\n"
        "- 風險段須說明波動的意義；紀律段須具體可執行。\n"
        "- 完整正文印在 stdout，不要只寫入檔案。\n"
        "- 不要加「工作摘要」或工具操作說明。\n"
    )


def build_portfolio_fix_prompt(
    *,
    profile_label: str,
    risk_label: str,
    facts_summary: str,
    previous_body: str,
    issues_block: str,
    mode: str = "beginner",
) -> str:
    if mode == "theme":
        return (
            f"上一版「{profile_label}主題組合」未通過自動驗證。\n"
            f"請依下列問題修正後，輸出完整新版正文到 stdout（Markdown）。\n\n"
            f"組合名稱：{profile_label}（{risk_label}）\n\n"
            f"=== 系統組合事實（facts，權重/角色/持股以此為準）===\n{facts_summary}\n"
            f"=== facts 結束 ===\n\n"
            f"驗證問題（含修正指引）：\n{issues_block}\n\n"
            "修正要求：\n"
            "- 這是主題袖口，不是新手全倉分散組合。\n"
            "- 不可更動系統權重/金額，不可加入未列出的股票。\n"
            "- 須含六段：一句話總結、適合誰、每檔為什麼選它、風險、部位紀律、免責。\n"
            "- 風險須提到主題集中；紀律須涵蓋：下跌/退潮應對、分批進場、定期檢視主題。\n"
            "- 不可出現「保證/穩賺/一定漲/目標價」等字眼。\n"
            "- 不要加工作摘要或工具操作說明。\n\n"
            "上一版全文：\n"
            f"{previous_body.strip()}\n"
        )

    return (
        f"上一版「{profile_label}投資組合建議」未通過自動驗證。\n"
        f"請依下列問題修正後，輸出完整新版正文到 stdout（Markdown）。\n\n"
        f"風險屬性：{profile_label}（{risk_label}）\n\n"
        f"=== 系統組合事實（facts，權重/角色/持股以此為準）===\n{facts_summary}\n"
        f"=== facts 結束 ===\n\n"
        f"驗證問題（含修正指引）：\n{issues_block}\n\n"
        "修正要求：\n"
        "- 對象是新手：白話、避免術語、必要術語一句話解釋。\n"
        "- 不可更動系統權重/金額，不可加入未列出的股票。\n"
        "- 須含六段：一句話總結、適合誰、每檔為什麼選它、風險、新手紀律、免責。\n"
        "- 新手紀律須涵蓋：下跌怎麼辦、分批進場、定期檢視/再平衡。\n"
        "- 不可出現「保證/穩賺/一定漲/目標價」等字眼。\n"
        "- 不要加工作摘要或工具操作說明。\n\n"
        "上一版全文：\n"
        f"{previous_body.strip()}\n"
    )
